-- PostgreSQL / Supabase. Chạy sau db/schema/test_automation_db_schema.sql và 007_seed_users.sql.
-- Chạy lại nhiều lần vẫn an toàn. Khớp với backend/src: TemplateRepository, RunRepository, LogRepository.

CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 1) test_runs ----------------------------------------------------------
-- Schema gốc đã có: environment, ci_run_id, tester_id, started_at, finished_at, created_at.
-- Chỉ thiếu tên run, cấu hình để "Chạy lại" và một cột ghi đè trạng thái.
--
-- Trạng thái KHÔNG lưu thành cột riêng, RunRepository tính ra:
--   finished_at IS NULL                      → running
--   final_status IS NOT NULL                 → final_status (hủy / lỗi kích hoạt: chưa có dòng test_results nào)
--   có test_results failed hoặc timedOut     → failed
--   có test_results interrupted              → interrupted
--   còn lại                                  → passed
-- Nên /ingest/runs/:id/finish chỉ cần ghi finished_at, không phải ghi final_status.
ALTER TABLE test_runs
  ADD COLUMN IF NOT EXISTS run_name     VARCHAR(255),
  ADD COLUMN IF NOT EXISTS config_json  JSONB,
  ADD COLUMN IF NOT EXISTS final_status VARCHAR(20);

-- Run tạo từ dashboard chưa biết trình duyệt thật (workflow quyết định), nên cho giá trị mặc định.
-- /ingest/runs có thể ghi đè browser khi workflow báo "bắt đầu chạy".
ALTER TABLE test_runs
  ALTER COLUMN started_at SET DEFAULT now(),
  ALTER COLUMN browser    SET DEFAULT 'chromium';

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_test_runs_final_status') THEN
    ALTER TABLE test_runs
      ADD CONSTRAINT ck_test_runs_final_status
      CHECK (final_status IS NULL OR final_status IN ('passed', 'failed', 'interrupted'));
  END IF;
END $$;

-- Lọc lịch sử theo thời gian và tên.
CREATE INDEX IF NOT EXISTS ix_test_runs_created_at ON test_runs (created_at DESC);

-- 2) test_templates -------------------------------------------------------
-- Tên cột env / timeout đúng như TemplateRepository. created_by cùng kiểu với users.user_id.
CREATE TABLE IF NOT EXISTS test_templates (
    template_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_name VARCHAR(255) NOT NULL UNIQUE,
    description   TEXT,
    scope         VARCHAR(50)  NOT NULL DEFAULT 'UI' CHECK (scope IN ('UI', 'API', 'DB')),
    target_json   JSONB        NOT NULL,                       -- { suiteId } hoặc { testIds: [...] }
    env           VARCHAR(50)  NOT NULL DEFAULT 'development',
    timeout       INTEGER      NOT NULL DEFAULT 30000,         -- mili-giây
    created_by    INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

DROP TRIGGER IF EXISTS trg_test_templates_updated_at ON test_templates;
CREATE TRIGGER trg_test_templates_updated_at BEFORE UPDATE ON test_templates
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 3) run_logs: bảng tạm cho khung log trực tiếp, xóa khi run kết thúc ---------
CREATE TABLE IF NOT EXISTS run_logs (
    log_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id     INTEGER NOT NULL REFERENCES test_runs(run_id) ON DELETE CASCADE,
    seq        INTEGER NOT NULL,
    level      VARCHAR(10) NOT NULL DEFAULT 'info' CHECK (level IN ('info', 'warn', 'error')),
    message    TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (run_id, seq)
);
