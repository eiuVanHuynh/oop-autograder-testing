CREATE TABLE IF NOT EXISTS test_templates (
  template_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_name VARCHAR(255) NOT NULL UNIQUE,
  description   TEXT NULL,
  scope         VARCHAR(50) NULL,
  target_json   JSONB NOT NULL,            -- { suiteId } hoac { testIds: ['TC-01', ...] }
  env           VARCHAR(50) NULL,
  timeout       INTEGER NULL,
  created_by    INT NULL REFERENCES users(user_id) ON DELETE SET NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE test_runs
  ADD COLUMN IF NOT EXISTS run_name    VARCHAR(255),
  ADD COLUMN IF NOT EXISTS config_json JSONB;

-- Bang tam: log bi xoa sau khi run ket thuc
CREATE TABLE IF NOT EXISTS run_logs (
  log_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id     INT NOT NULL REFERENCES test_runs(run_id) ON DELETE CASCADE,
  seq        INTEGER NOT NULL,
  level      VARCHAR(10) NOT NULL DEFAULT 'info' CHECK (level IN ('info','warn','error')),
  message    TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (run_id, seq)
);

-- Hai cot nhom DB them o nhanh cua ho (schema cua ho con la MySQL nen khong nap
-- truc tiep duoc); dich sang Postgres o day.
ALTER TABLE test_cases
  ADD COLUMN IF NOT EXISTS execution_status VARCHAR(15) NOT NULL DEFAULT 'pending'
    CHECK (execution_status IN ('pending','in_progress','done','reopened'));

ALTER TABLE test_runs
  ADD COLUMN IF NOT EXISTS execution_type VARCHAR(15) NOT NULL DEFAULT 'automation'
    CHECK (execution_type IN ('automation','manual'));

-- Bang noi template <-> test case. automation/scripts/export-report.js doc bang
-- nay de biet pham vi bao cao. Ban cua nhom DB o db/schema con la MySQL
-- (INT UNSIGNED / ENGINE=InnoDB) nen dich sang Postgres o day.
CREATE TABLE IF NOT EXISTS template_test_cases (
  template_id INT NOT NULL REFERENCES test_templates(template_id) ON DELETE CASCADE,
  test_id     INT NOT NULL REFERENCES test_cases(test_id) ON DELETE CASCADE,
  PRIMARY KEY (template_id, test_id)
);
