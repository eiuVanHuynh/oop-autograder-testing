CREATE TABLE IF NOT EXISTS rerun_requests (
    request_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id       INTEGER NOT NULL,
    reason       TEXT NULL,
    status       VARCHAR(10) NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending', 'approved', 'rejected')),
    requested_by INTEGER NULL,
    decided_by   INTEGER NULL,
    decided_at   TIMESTAMPTZ NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_rerun_requests_run FOREIGN KEY (run_id)
        REFERENCES test_runs(run_id) ON DELETE CASCADE,
    CONSTRAINT fk_rerun_requests_requester FOREIGN KEY (requested_by)
        REFERENCES users(user_id) ON DELETE SET NULL,
    CONSTRAINT fk_rerun_requests_decider FOREIGN KEY (decided_by)
        REFERENCES users(user_id) ON DELETE SET NULL
);

-- Hang doi cho duyet: trang cua Admin/Tester loc theo status.
CREATE INDEX IF NOT EXISTS ix_rerun_requests_status ON rerun_requests (status);
CREATE INDEX IF NOT EXISTS ix_rerun_requests_run ON rerun_requests (run_id);

-- Moi run chi duoc co MOT yeu cau dang cho: bam nut hai lan (hoac hai Dev cung xin) khong duoc
-- sinh ra hai dong cho Admin duyet rieng. Da duyet/tu choi roi thi xin lai duoc.
CREATE UNIQUE INDEX IF NOT EXISTS ux_rerun_requests_pending
    ON rerun_requests (run_id) WHERE status = 'pending';

DROP TRIGGER IF EXISTS trg_rerun_requests_updated_at ON rerun_requests;
CREATE TRIGGER trg_rerun_requests_updated_at BEFORE UPDATE ON rerun_requests
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
