CREATE TABLE IF NOT EXISTS bugs (
    bug_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_id   INTEGER NOT NULL,
    title       VARCHAR(255) NOT NULL,
    description TEXT NULL,
    severity    VARCHAR(10)  NOT NULL CHECK (severity IN ('low', 'medium', 'high', 'critical')),
    status      VARCHAR(15)  NOT NULL DEFAULT 'new'
                CHECK (status IN ('new', 'in_progress', 'fixed', 'closed')),
    created_by  INTEGER NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_bugs_result FOREIGN KEY (result_id)
        REFERENCES test_results(execution_id) ON DELETE CASCADE,
    CONSTRAINT fk_bugs_user FOREIGN KEY (created_by)
        REFERENCES users(user_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS ix_bugs_status ON bugs (status);
CREATE INDEX IF NOT EXISTS ix_bugs_result ON bugs (result_id);

DROP TRIGGER IF EXISTS trg_bugs_updated_at ON bugs;
CREATE TRIGGER trg_bugs_updated_at BEFORE UPDATE ON bugs
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
